#include <stdio.h>
int main(){
    int a[5][5]={
        // {85,67,95,65},
        // {80,95,86,56},
        // {100,98,67,86},
        // {95,76,84,65},
        // {67,86,90,76},
    };
    for (int i=0; i<5;i++){
        for (int j=0;j<4;j++){
            scanf("%d",&a[i][j]);
            a[i][4] += a[i][j];
        }
    }

    for (int i=0; i<5;i++){
        printf("%d %.1f\n",a[i][4],a[i][4]/4.0);
    }

}